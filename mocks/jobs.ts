import { PricingLine } from '../lib/pricing';

export type JobStatus = 'Unassigned' | 'Accepted' | 'Picked up' | 'In transit' | 'Delivered' | 'Exception';

export interface JobTimelineEvent {
  id: string;
  status: JobStatus | 'Driver assigned' | 'Booking created' | 'Driver reassigned' | 'Exception noted';
  label: string;
  actor: string;
  timestamp: string;
  note?: string;
}

export interface JobNotification {
  id: string;
  channel: 'SMS' | 'Email';
  recipient: string;
  event: string;
  preview: string;
  sentAt: string;
  status: 'Sent' | 'Failed' | 'Queued';
}

export interface JobPOD {
  signatureDataUrl?: string; // canvas or svg data
  signatureSvgPath?: string;
  recipientName: string;
  timestamp: string;
  addressText: string;
  geotag: string;
  photoUrl?: string;
}

export interface JobException {
  code: 'UNAVAILABLE' | 'BAD_ADDRESS' | 'PAYMENT_HOLD' | 'DAMAGED' | 'DRIVER_DELAY';
  reason: string;
  timestamp: string;
  severity: 'Critical' | 'High' | 'Medium';
  evidenceNotes: string;
  photoPlaceholder?: string;
  resolved: boolean;
  resolution?: string;
  resolvedAt?: string;
}

export interface Job {
  id: string; // MRD-48xxxx
  customerName: string;
  customerType: 'business' | 'individual';
  customerEmail: string;
  customerPhone: string;
  fromSuburb: string;
  fromAddress: string;
  toSuburb: string;
  toAddress: string;
  depot: 'Melbourne' | 'Sydney' | 'Brisbane';
  service: 'sameday' | 'nextday' | 'scheduled';
  status: JobStatus;
  driverId?: string;
  driverName?: string;
  eta: string;
  deliveredAt?: string;
  price: number;
  distanceKm: number;
  createdAt: string;
  parcel: {
    description: string;
    type: 'document' | 'small' | 'medium' | 'large' | 'pallet';
    weightKg: number;
    dimensions: string;
    isFragile: boolean;
    signatureRequired: boolean;
  };
  pricingBreakdown: PricingLine[];
  timeline: JobTimelineEvent[];
  pod?: JobPOD;
  notifications: JobNotification[];
  exception?: JobException;
}

